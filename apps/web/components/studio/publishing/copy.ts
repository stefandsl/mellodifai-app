const DICT = { it, en } as const;

export function pt(
  lang: "it" | "en",
  key: string,
  vars: Record<string, string | number> = {},
): string {
  const text =
    (DICT[lang] as Record<string, string>)[key] ??
    (DICT.it as Record<string, string>)[key] ??
    key;
  return text.replace(/\{(\w+)\}/gu, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}
