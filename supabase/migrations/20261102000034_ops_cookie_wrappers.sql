create function ops.admin_resolve_kie_submission(p_ctx jsonb, p_version uuid, p_charged boolean, p_task_id text default null, p_edit uuid default null) returns jsonb
language plpgsql security definer set search_path = '' set timezone = 'UTC' as $$
declare a record; data jsonb; err jsonb; detail text; v_actor_key text; owned_version public.versions%rowtype; idem public.idempotency_keys%rowtype; ids jsonb; jid uuid; r public.reservations%rowtype; estimate jsonb; edit public.section_edits%rowtype;
begin
  perform ops._enter();
  select null::uuid user_id,null::text actor_kind,null::uuid token_id,false remote into a;
  begin
    select * into a from ops._actor(p_ctx);
    v_actor_key := a.actor_kind||':'||coalesce(a.token_id,a.user_id)::text;
    if a.actor_kind <> 'session' or a.role <> 'admin' or a.remote then raise exception 'admin required'; end if;
    select * into owned_version from public.versions where id=p_version and owner_id=a.user_id for update;
    if not found then raise exception 'owned version required'; end if;
    if owned_version.test_run <> a.test_mode then raise exception 'test rule required' using errcode='MDF04'; end if;
    if p_ctx ? 'idempotency_key' then
      if length(p_ctx->>'idempotency_key') not between 8 and 100 or coalesce(p_ctx->>'request_hash','')='' then raise exception 'invalid idempotency input'; end if;
      insert into public.idempotency_keys(actor_key,key,request_hash,state) values(v_actor_key,p_ctx->>'idempotency_key',p_ctx->>'request_hash','in_flight') on conflict do nothing;
      select * into idem from public.idempotency_keys i where i.actor_key=v_actor_key and i.key=p_ctx->>'idempotency_key' for update;
      if found then
        if idem.request_hash <> p_ctx->>'request_hash' then
          insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,error_code,remote) values(a.user_id,a.actor_kind,a.token_id,'admin_resolve_kie_submission',coalesce(p_ctx->>'request_hash',''),'error','idempotency_mismatch',a.remote);
          perform ops._enter();
          return jsonb_build_object('ok',false,'code','idempotency_mismatch','message','Idempotency key used for another request');
        end if;
        if idem.state='done' then
          insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,error_code,remote) values(a.user_id,a.actor_kind,a.token_id,'admin_resolve_kie_submission',coalesce(p_ctx->>'request_hash',''),'ok',null,a.remote);
          perform ops._enter(); return idem.response;
        end if;
      end if;
    end if;
    perform set_config('request.jwt.claim.sub',a.user_id::text,true);
    perform set_config('request.jwt.claim.role','authenticated',true);
    perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'role','authenticated')::text,true);
    if auth.uid() is distinct from a.user_id then raise exception 'claim required' using errcode='MDF03'; end if;
    perform set_config('mdf.job_ctx',jsonb_build_object('token_id',a.token_id,'run_id',p_ctx->>'run_id','fake_providers',a.test_mode)::text,true);
    if p_edit is null then
      perform public.resolve_kie_submission(p_version,p_charged,p_task_id);
    else
      select * into edit from public.section_edits where id=p_edit and version_id=p_version and owner_id=a.user_id for update;
      if not found then raise exception 'owned rewrite required'; end if;
      if p_charged is null or edit.kie_submit_state is distinct from 'submitting' or edit.kie_task_id is not null
        or edit.kept_take_id is not null or edit.discarded_at is not null then raise exception 'unknown submission required'; end if;
      if exists(select 1 from public.jobs where version_id=p_version and status in ('queued','running')) then raise exception 'job already active'; end if;
      if p_charged then
        if coalesce(length(btrim(p_task_id)),0)=0 or p_task_id ~ '[[:space:][:cntrl:]]' then raise exception 'task id required'; end if;
        update public.section_edits set kie_submit_state='submitted',kie_task_id=btrim(p_task_id) where id=p_edit;
        insert into public.jobs(owner_id,version_id,stage,idempotency_key,payload)
          values(a.user_id,p_version,'replace_section','replace_section:'||p_edit||':resolved:'||gen_random_uuid(),
            jsonb_build_object('edit_id',p_edit,'take_id',edit.take_id));
      else
        update public.section_edits set kie_submit_state=null,kie_task_id=null where id=p_edit;
      end if;
    end if;
    -- Resolve only the submission represented by this generation or section edit.
    for r in select * from public.reservations where version_id=p_version and user_id=a.user_id
      and state='ambiguous' and kie_submit_reserved
      and ((p_edit is null and section_edit_id is null and kie_generation=owned_version.kie_generation)
        or (p_edit is not null and section_edit_id=p_edit)) for update
    loop
      -- Confirm the pre-submit entry before close counts any still-open estimate.
      update public.spend_entries set
        items=case when p_charged then items_est else (select jsonb_object_agg(key,0) from jsonb_each(items_est)) end,
        usd=case when p_charged then usd_est else 0 end,state='settled',settled_at=now()
        where reservation_id=r.id and provider='kie' and state='open';
      if p_charged and not exists(select 1 from public.spend_entries where reservation_id=r.id and provider='kie') then
        select e into estimate from jsonb_array_elements(r.estimate) e where e->>'provider'='kie' limit 1;
        if estimate is null then raise exception 'price_missing' using errcode='MDF05'; end if;
        insert into public.spend_entries(reservation_id,call_key,provider,model,items_est,usd_est,items,usd,state,settled_at)
          values(r.id,'kie:admin-resolved-submit','kie',estimate->>'model',estimate->'items',(estimate->>'usd')::numeric,
            estimate->'items',(estimate->>'usd')::numeric,'settled',now());
      end if;
      perform ops._reconcile_spend(r.id,true);
      update public.reservations set state='closed',closed_at=now() where id=r.id;
    end loop;
    ids := coalesce(nullif(current_setting('mdf.job_ids',true),''),'[]')::jsonb;
    for jid in select jobs.id from public.jobs jobs where jobs.owner_id=a.user_id and jobs.id in (select value::uuid from jsonb_array_elements_text(ids)) loop
      perform ops.reserve_job(jid);
    end loop;
    select jsonb_build_object('jobs',coalesce(jsonb_agg(jsonb_build_object('job_id',j.id,'version_id',j.version_id,'stage',j.stage) order by j.created_at,j.id),'[]'::jsonb)) || coalesce(data,'{}'::jsonb)
      into data from public.jobs j where j.owner_id=a.user_id and j.id in (select value::uuid from jsonb_array_elements_text(ids));
    update public.idempotency_keys i set state='done',response=jsonb_build_object('ok',true,'data',data)
      where i.actor_key=v_actor_key and i.key=p_ctx->>'idempotency_key' and i.request_hash=p_ctx->>'request_hash';
  exception when others then
    get stacked diagnostics detail = pg_exception_detail;
    err := ops.map_error(sqlstate,sqlerrm);
    delete from public.idempotency_keys i where i.actor_key=v_actor_key and i.key=p_ctx->>'idempotency_key' and i.request_hash=p_ctx->>'request_hash' and i.state='in_flight';
    insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,error_code,remote)
      values(a.user_id,coalesce(a.actor_kind,'unknown'),a.token_id,'admin_resolve_kie_submission',coalesce(p_ctx->>'request_hash',''),'error',err->>'code',coalesce(a.remote,false));
    perform ops._enter();
    return jsonb_build_object('ok',false,'code',err->>'code','message',case when err->>'code'='internal' then 'Internal error' else sqlerrm end,
      'details',jsonb_build_object('reason',err->>'reason') || case when sqlstate='MDF02' and sqlerrm like 'cap_exceeded:%' then jsonb_build_object('scope',split_part(sqlerrm,':',2),'provider',split_part(sqlerrm,':',3),'unit',split_part(sqlerrm,':',4),'period',split_part(sqlerrm,':',5)) else '{}'::jsonb end || case when detail like '{%' then detail::jsonb else '{}'::jsonb end);
  end;
  insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,remote)
    values(a.user_id,a.actor_kind,a.token_id,'admin_resolve_kie_submission',coalesce(p_ctx->>'request_hash',''),'ok',a.remote);
  perform ops._enter();
  return jsonb_build_object('ok',true,'data',data);
end;
$$;
