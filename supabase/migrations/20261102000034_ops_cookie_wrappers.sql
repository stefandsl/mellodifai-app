-- Cookie-only operations and local administrative operations.

create table public.web_tool_usage (
  user_id uuid not null references public.profiles(id) on delete cascade,
  tool text not null check (tool in ('style_format','transcribe')),
  day date not null, used integer not null default 0,
  primary key (user_id, tool, day)
);
alter table public.web_tool_usage enable row level security;
revoke all on public.web_tool_usage from public, anon, authenticated, mdf_web, mdf_auth, service_role;

create function ops.style_format_check(p_ctx jsonb) returns jsonb
language plpgsql security definer set search_path = '' set timezone = 'UTC' as $$
declare a record; data jsonb; err jsonb; detail text; usage_day date; used_count integer; retry_seconds integer;
begin
  perform ops._enter();
  select null::uuid user_id,null::text actor_kind,null::uuid token_id,false remote into a;
  begin
    select * into a from ops._actor(p_ctx);
    if a.actor_kind <> 'session' then raise exception 'admin required'; end if;

    perform set_config('request.jwt.claim.sub',a.user_id::text,true);
    perform set_config('request.jwt.claim.role','authenticated',true);
    perform set_config('request.jwt.claims',jsonb_build_object('sub',a.user_id,'role','authenticated')::text,true);
    if auth.uid() is distinct from a.user_id then raise exception 'claim required' using errcode='MDF03'; end if;
    perform set_config('mdf.job_ctx',jsonb_build_object('token_id',a.token_id,'run_id',p_ctx->>'run_id','fake_providers',a.test_mode)::text,true);
    if a.role <> 'admin' then
      usage_day := (now() at time zone 'Europe/Rome')::date;
      insert into public.web_tool_usage(user_id,tool,day,used) values(a.user_id,'style_format',usage_day,1)
        on conflict(user_id,tool,day) do update set used=public.web_tool_usage.used+1
        where public.web_tool_usage.used < 20 returning used into used_count;
      if not found then
        retry_seconds := ceil(extract(epoch from (((usage_day+1)::timestamp at time zone 'Europe/Rome')-now())))::integer;
        insert into public.audit_log(owner_id,actor_kind,operation,args_hash,result,error_code,remote)
          values(a.user_id,a.actor_kind,'style_format_check',coalesce(p_ctx->>'request_hash',''),'error','rate_limited',a.remote);
        perform ops._enter();
        return jsonb_build_object('ok',false,'code','rate_limited','message','Daily tool limit reached','retry_after',retry_seconds);
      end if;
    end if;
    data := '{}'::jsonb;
  exception when others then
    get stacked diagnostics detail = pg_exception_detail;
    err := ops.map_error(sqlstate,sqlerrm);
    insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,error_code,remote)
      values(a.user_id,coalesce(a.actor_kind,'unknown'),a.token_id,'style_format_check',coalesce(p_ctx->>'request_hash',''),'error',err->>'code',coalesce(a.remote,false));
    perform ops._enter();
    return jsonb_build_object('ok',false,'code',err->>'code','message',case when err->>'code'='internal' then 'Internal error' else sqlerrm end,
      'details',jsonb_build_object('reason',err->>'reason') || case when sqlstate='MDF02' and sqlerrm like 'cap_exceeded:%' then jsonb_build_object('scope',split_part(sqlerrm,':',2),'provider',split_part(sqlerrm,':',3),'unit',split_part(sqlerrm,':',4),'period',split_part(sqlerrm,':',5)) else '{}'::jsonb end || case when detail like '{%' then detail::jsonb else '{}'::jsonb end);
  end;
  insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,remote)
    values(a.user_id,a.actor_kind,a.token_id,'style_format_check',coalesce(p_ctx->>'request_hash',''),'ok',a.remote);
  perform ops._enter();
  return jsonb_build_object('ok',true,'data',data);
end;
$$;
alter function ops.style_format_check(jsonb) owner to postgres;
revoke execute on function ops.style_format_check(jsonb) from public, anon, authenticated;
