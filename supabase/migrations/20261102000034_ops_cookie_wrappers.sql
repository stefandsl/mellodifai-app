  end;
  insert into public.audit_log(owner_id,actor_kind,token_id,operation,args_hash,result,remote)
    values(a.user_id,a.actor_kind,a.token_id,'admin_resolve_upload',coalesce(p_ctx->>'request_hash',''),'ok',a.remote);
  perform ops._enter();
